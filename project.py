import pandas as pd
import pickle
from sklearn.preprocessing import LabelEncoder
from sklearn.preprocessing import MinMaxScaler
from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestRegressor
from sklearn.neighbors import KNeighborsRegressor
from imblearn.under_sampling import RandomUnderSampler
from sklearn.metrics import r2_score

df=pd.read_csv('/content/Daily_Water_Intake.csv')
df

categorical_cols=['Gender','Physical Activity Level','Weather','Hydration Level']
encoders={}
for col in categorical_cols:
    le=LabelEncoder()
    df[col] = le.fit_transform(df[col])
    encoders[col]=le

df

Features=df.iloc[:,0:-1]
Features

Target=df.iloc[:,-1]
Target

Target.value_counts()

us=RandomUnderSampler(random_state=42)
features,target=us.fit_resample(Features,Target)
target.value_counts()

features_train,features_test,target_train,target_test=train_test_split(features,target,test_size=0.3,random_state=1)

RFC=RandomForestRegressor(random_state=42)
RFC.fit(features_train,target_train)

RF_pred=RFC.predict(features_test)
print(r2_score(target_test,RF_pred)*100)

KNN=KNeighborsRegressor(n_neighbors=3)
KNN.fit(features_train,target_train)

KNN_pred=KNN.predict(features_test)
print(r2_score(target_test,KNN_pred)*100)

pickle.dump(RFC,open('model_RFC.sav','wb'))

pickle.dump(KNN,open('model_KNN.sav','wb'))

pickle.dump(encoders,open("encoders.sav", "wb"))